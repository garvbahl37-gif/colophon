import { writeFileSync } from "node:fs";

/**
 * Redraws the README's evaluation chart from the run that just happened.
 *
 * A hand-made chart of measured numbers goes stale the first time anyone reruns
 * the suite, and stale in the most damaging direction: it keeps showing the
 * result someone was happy with. Regenerating it here means the picture in the
 * README cannot disagree with results.json, and a retrieval change arrives in
 * the same diff as both.
 */

interface Variant {
  name: string;
  shipped: boolean;
  scores: { ndcg: number; ms: number };
}

export function writeChart(data: {
  k: number;
  chunks: number;
  questions: number;
  models: { embed: string; rerank: string };
  variants: Variant[];
}): void {
  const W = 430;
  const X = 250;
  const best = Math.max(...data.variants.map((v) => v.scores.ndcg));

  let y = 74;
  const bars = data.variants
    .map((v) => {
      const width = Math.round(W * (v.scores.ndcg / best) * 10) / 10;
      const tone = v.scores.ndcg === best ? "win" : v.shipped ? "ship" : "bar";
      const row = `    <text class="tx" x="30" y="${y + 11}">${v.name}</text>
    <rect class="track" x="${X}" y="${y}" width="${W}" height="14"/>
    <rect class="${tone} grow" x="${X}" y="${y}" width="${width}" height="14"/>
    <text class="num" x="${X + W + 12}" y="${y + 11}">${v.scores.ndcg.toFixed(3)}</text>
    <text class="dim" x="${X + W + 62}" y="${y + 11}">${Math.round(v.scores.ms)}ms</text>`;
      y += 30;
      return row;
    })
    .join("\n");

  // Room for the two caption lines; sizing from content rather than a constant
  // is what stops them being clipped when a variant is added.
  const height = y + 72;

  writeFileSync(
    new URL("../docs/evaluation.svg", import.meta.url),
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 860 ${height}" width="860" height="${height}"
     role="img" aria-label="Retrieval evaluation: nDCG at ${data.k} for ${data.variants.length} configurations over ${data.questions} questions and ${data.chunks} passages.">
  <style>
    .bg { fill: #ffffff; } .rule { stroke: #0a0a0a; } .hair { stroke: #d0d0d6; }
    .tx { fill: #0a0a0a; font-family: ui-monospace, "SF Mono", Menlo, monospace; font-size: 11px; }
    .num { fill: #0a0a0a; font-family: ui-monospace, "SF Mono", Menlo, monospace; font-size: 11px; font-weight: 700; }
    .dim { fill: #6b6b73; font-family: ui-monospace, "SF Mono", Menlo, monospace; font-size: 9px; }
    .track { fill: #efeff1; } .bar { fill: #8a8a93; }
    .win { fill: #1f8a56; } .ship { fill: #e8442a; }

    @media (prefers-color-scheme: dark) {
      .bg { fill: #0c0c0d; } .rule { stroke: #f4f4f5; } .hair { stroke: #3a3a40; }
      .tx { fill: #f4f4f5; } .num { fill: #f4f4f5; } .dim { fill: #8a8a93; }
      .track { fill: #1c1c1f; } .bar { fill: #71717a; } .win { fill: #34d399; }
    }

    /* Bars grow from zero once per cycle, on a shared scale, so the shipped
       configuration visibly falls short of the baseline rather than being drawn
       to look level with it. */
    .grow { transform-origin: ${X}px 0; animation: grow 6s ease-out infinite; }
    @keyframes grow {
      0% { transform: scaleX(0); } 18% { transform: scaleX(1); }
      92% { transform: scaleX(1); } 100% { transform: scaleX(0); }
    }
    @media (prefers-reduced-motion: reduce) { .grow { animation: none; } }
  </style>

  <rect class="bg" width="860" height="${height}"/>
  <line class="rule" x1="30" y1="26" x2="830" y2="26" stroke-width="2"/>
  <text class="dim" x="30" y="18">RETRIEVAL EVALUATION · nDCG@${data.k} · ${data.questions} questions · ${data.chunks} passages · distractors included</text>
  <text class="dim" x="30" y="${height - 6}">embed ${data.models.embed} · rerank ${data.models.rerank} — the chart says which run produced it, so an experiment cannot be mistaken for the shipped configuration.</text>

  <text class="dim" x="${X}" y="62">nDCG@${data.k} (shared scale)</text>
  <text class="dim" x="${X + W + 12}" y="62">score</text>
  <text class="dim" x="${X + W + 62}" y="62">latency</text>

${bars}

  <line class="hair" x1="30" y1="${y + 10}" x2="830" y2="${y + 10}" stroke-width="1"/>
  <text class="dim" x="30" y="${y + 28}">green = best measured · red = what ships. Regenerated by pnpm eval, so the picture cannot disagree with the numbers.</text>
  <text class="dim" x="30" y="${y + 41}">A small corpus flatters the baseline; production reranks with a different model. Neither is settled by this run.</text>
</svg>
`,
  );
}
